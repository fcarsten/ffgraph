#!/usr/bin/env python3
"""Losslessly migrate the historical ffgraph XPM/XBM tree to RGBA PNG.

Maintenance tool only: normal builds use the committed PNG files. Pass a copy
of the original icons directory (available in Git history) as --source.
"""
import argparse
import ast
import hashlib
from pathlib import Path
import re
import struct
import zlib


def xpm(path):
    # A few original files have unrelated binary data after the C array.
    text = path.read_bytes().split(b"};", 1)[0].decode("ascii")
    rows = [ast.literal_eval(m.group()) for m in re.finditer(r'"(?:[^"\\]|\\.)*"', text)]
    width, height, colors, cpp = map(int, rows[0].split()[:4])
    palette = {}
    for row in rows[1:colors + 1]:
        color = row[cpp:].strip().split()
        if color[0] != "c":
            raise ValueError(f"Unsupported palette in {path}: {row}")
        value = color[1]
        if value.lower() == "none":
            rgba = bytes((0, 0, 0, 0))
        elif re.fullmatch(r"#[0-9a-fA-F]{3}([0-9a-fA-F]{3})?", value):
            value = value[1:]
            if len(value) == 3:
                value = "".join(c * 2 for c in value)
            rgba = bytes.fromhex(value) + b"\xff"
        else:
            raise ValueError(f"Unsupported color in {path}: {value}")
        palette[row[:cpp]] = rgba
    pixels = rows[colors + 1:colors + 1 + height]
    if len(pixels) != height or any(len(row) != width * cpp for row in pixels):
        raise ValueError(f"Invalid XPM dimensions in {path}")
    return width, height, b"".join(palette[row[x:x + cpp]]
                                   for row in pixels for x in range(0, width * cpp, cpp))


def xbm(path):
    text = path.read_text()
    width = int(re.search(r"#define\s+\S+_width\s+(\d+)", text)[1])
    height = int(re.search(r"#define\s+\S+_height\s+(\d+)", text)[1])
    # All bundled sources are byte arrays, with LSB-first pixels and row padding.
    data = re.search(r"static\s+(?:unsigned\s+)?char\s+\S+\[\]\s*=\s*\{([^}]*)", text)[1]
    values = [int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]+)", data)]
    stride = (width + 7) // 8
    if len(values) != stride * height:
        raise ValueError(f"Invalid XBM dimensions in {path}")
    return width, height, bytes(v for y in range(height) for x in range(width)
                               for v in (0, 0, 0, 255 if values[y * stride + x // 8] & (1 << (x % 8)) else 0))


def png(width, height, rgba):
    def chunk(kind, payload):
        return struct.pack(">I", len(payload)) + kind + payload + struct.pack(">I", zlib.crc32(kind + payload))
    scanlines = b"".join(b"\0" + rgba[y * width * 4:(y + 1) * width * 4] for y in range(height))
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(scanlines, 9)) + chunk(b"IEND", b""))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True, help="Destination icons directory")
    parser.add_argument("--manifest", type=Path, required=True)
    args = parser.parse_args()
    aliases = ["# Generated by scripts/convert-legacy-icons.py. Values are relative to ICON_LIB_DIR.",
               "namespace eval ::ffgraph_icons { variable aliases [dict create \\"]
    manifest = ["# legacy-path\tpng-path\twidth\theight\trgba-crc32\tsource-sha256"]
    sources = sorted(args.source.glob("xpm/*")) + sorted(args.source.glob("xbm/*.xbm"))
    # Path.glob includes the original hidden .xpm file; exclude CVS metadata.
    sources = [p for p in sources if p.is_file() and (p.suffix == ".xpm" or p.name == ".xpm" or p.suffix == ".xbm")]
    if not sources:
        parser.error("The source directory contains no legacy XPM/XBM assets")
    for source in sources:
        monochrome = source.suffix == ".xbm"
        width, height, rgba = xbm(source) if monochrome else xpm(source)
        name = "unnamed-xpm" if source.name == ".xpm" else source.stem
        target = Path("png") / ("xbm" if monochrome else "") / (name + ".png")
        destination = args.output / target
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(png(width, height, rgba))
        legacy = source.relative_to(args.source).as_posix()
        aliases.append(f"    {legacy} {target.as_posix()} \\")
        manifest.append(f"{legacy}\t{target.as_posix()}\t{width}\t{height}\t{zlib.crc32(rgba)}\t"
                        + hashlib.sha256(source.read_bytes()).hexdigest())
    aliases.append("] }")
    (args.output / "legacy-icons.tcl").write_text("\n".join(aliases) + "\n")
    args.manifest.write_text("\n".join(manifest) + "\n")
    print(f"Converted {len(sources)} images without external image libraries")


if __name__ == "__main__":
    main()
